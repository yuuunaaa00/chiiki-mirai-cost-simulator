IN_COST = {13, 29, 121, 135}


def main():
    data = json.load(open(DATA, encoding="utf-8"))
    out = {}
    for i, e in enumerate(data):
        if i in KNOWN:
            v = KNOWN[i]
            if isinstance(v, str):
                provided, label = P[v]
            elif isinstance(v[0], str):
                provided, label = P[v[0]][0], v[1]
            else:
                provided, label = v
            rec = {"status": "known", "provided_per_month": provided, "label": label}
        elif i in NONE:
            rec = {"status": "none", "provided_per_month": 0, "label": NONE[i]}
        elif i in IN_COST:
            rec = {"status": "in_cost", "provided_per_month": None,
                   "label": "自炊等の食費の目安が生活費に含まれています"}
        else:
            rec = {"status": "unknown", "provided_per_month": None, "label": "公表資料から確認できませんでした"}
        rec["name"] = e["name"]
        out[e["id"]] = rec
    json.dump(out, open(OUT, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    from collections import Counter
    print(Counter(r["status"] for r in out.values()))

if __name__ == "__main__":
    main()
